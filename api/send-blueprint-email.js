export default async function handler(req, res) {
  if (req.method !== 'POST') return res.status(405).end();

  const { blueprint, email } = req.body;
  const { business_name, what_you_do, main_goal, biggest_challenge, success_in_90_days, roadmap } = blueprint;

  const html = `
<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <style>
    body { font-family: Arial, sans-serif; max-width: 800px; margin: 0 auto; padding: 40px 20px; color: #1a1a1a; }
    .header { background: linear-gradient(135deg, #7c3aed, #2563eb); padding: 40px; border-radius: 12px; color: white; margin-bottom: 32px; }
    .header h1 { margin: 0 0 8px; font-size: 28px; }
    .header p { margin: 0; opacity: 0.85; font-size: 15px; }
    .phase { border: 1px solid #e5e7eb; border-radius: 12px; padding: 24px; margin-bottom: 20px; }
    .phase-1 { border-left: 4px solid #7c3aed; }
    .phase-2 { border-left: 4px solid #2563eb; }
    .phase-3 { border-left: 4px solid #0d9488; }
    .phase h2 { margin: 0 0 4px; font-size: 20px; }
    .timeframe { color: #6b7280; font-size: 13px; margin-bottom: 12px; }
    .focus { background: #f9fafb; padding: 12px 16px; border-radius: 8px; font-size: 14px; margin-bottom: 16px; color: #374151; }
    .actions { list-style: none; padding: 0; margin: 0; }
    .actions li { padding: 8px 0; border-bottom: 1px solid #f3f4f6; font-size: 14px; display: flex; align-items: flex-start; gap: 8px; }
    .actions li:last-child { border-bottom: none; }
    .actions li::before { content: "✓"; color: #10b981; font-weight: bold; flex-shrink: 0; }
    .summary { background: #f9fafb; border-radius: 12px; padding: 24px; margin-bottom: 24px; }
    .summary h3 { margin: 0 0 16px; font-size: 16px; }
    .summary-grid { display: grid; grid-template-columns: 1fr 1fr; gap: 12px; }
    .summary-item label { font-size: 11px; text-transform: uppercase; color: #9ca3af; letter-spacing: 0.05em; }
    .summary-item p { margin: 2px 0 0; font-size: 14px; font-weight: 500; }
    .footer { text-align: center; margin-top: 40px; padding-top: 24px; border-top: 1px solid #e5e7eb; color: #9ca3af; font-size: 13px; }
  </style>
</head>
<body>
  <div class="header">
    <h1>Your 90-Day Marketing Blueprint</h1>
    <p>${business_name} — Generated by Fire-Works Blueprint Builder</p>
  </div>

  <div class="summary">
    <h3>Business Summary</h3>
    <div class="summary-grid">
      <div class="summary-item">
        <label>Business</label>
        <p>${business_name}</p>
      </div>
      <div class="summary-item">
        <label>What You Do</label>
        <p>${what_you_do}</p>
      </div>
      <div class="summary-item">
        <label>Main Goal</label>
        <p>${main_goal}</p>
      </div>
      <div class="summary-item">
        <label>Biggest Challenge</label>
        <p>${biggest_challenge}</p>
      </div>
      <div class="summary-item">
        <label>Success in 90 Days</label>
        <p>${success_in_90_days}</p>
      </div>
    </div>
  </div>

  <div class="phase phase-1">
    <h2>${roadmap.phase1.title}</h2>
    <div class="timeframe">${roadmap.phase1.timeframe}</div>
    <div class="focus">${roadmap.phase1.focus}</div>
    <ul class="actions">
      ${roadmap.phase1.actions.map(a => `<li>${a}</li>`).join('')}
    </ul>
  </div>

  <div class="phase phase-2">
    <h2>${roadmap.phase2.title}</h2>
    <div class="timeframe">${roadmap.phase2.timeframe}</div>
    <div class="focus">${roadmap.phase2.focus}</div>
    <ul class="actions">
      ${roadmap.phase2.actions.map(a => `<li>${a}</li>`).join('')}
    </ul>
  </div>

  <div class="phase phase-3">
    <h2>${roadmap.phase3.title}</h2>
    <div class="timeframe">${roadmap.phase3.timeframe}</div>
    <div class="focus">${roadmap.phase3.focus}</div>
    <ul class="actions">
      ${roadmap.phase3.actions.map(a => `<li>${a}</li>`).join('')}
    </ul>
  </div>

  <div class="footer">
    <p>Generated by Fire-Works Blueprint Builder — A Kelowna Media Tool</p>
    <p>Questions? Email us at colonnamedia@gmail.com</p>
  </div>
</body>
</html>
  `;

  await fetch('https://api.resend.com/emails', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${process.env.RESEND_API_KEY}`
    },
    body: JSON.stringify({
      from: 'Fire-Works Blueprint <onboarding@resend.dev>',
      to: email,
      subject: `Your 90-Day Marketing Blueprint — ${business_name}`,
      html
    })
  });

  // Mark email as sent
  const { Pool } = await import('pg');
  const pool = new Pool({
    connectionString: process.env.NEON_DATABASE_URL,
    ssl: { rejectUnauthorized: false }
  });
  await pool.query(
    `UPDATE blueprints SET email_sent = true WHERE id = $1`,
    [blueprint.id]
  );

  return res.status(200).json({ success: true });
}
